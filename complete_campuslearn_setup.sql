-- 1. Auto-create profile on user signup
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER AS $$
BEGIN
  INSERT INTO public.profiles (id, email, full_name, is_admin)
  VALUES (
    NEW.id,
    NEW.email,
    COALESCE(NEW.raw_user_meta_data->>'full_name', split_part(NEW.email, '@', 1)),
    FALSE
  )
  ON CONFLICT (id) DO UPDATE SET email = EXCLUDED.email;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();

-- 2. Check pending invites on profile insert
CREATE OR REPLACE FUNCTION public.handle_new_profile_invite()
RETURNS TRIGGER AS $$
BEGIN
  IF EXISTS (SELECT 1 FROM public.coordinator_invites WHERE email = NEW.email AND status = 'pending') THEN
    UPDATE public.profiles SET is_coordinator = TRUE WHERE id = NEW.id;
    INSERT INTO public.user_roles (user_id, role) VALUES (NEW.id, 'coordinator') ON CONFLICT DO NOTHING;
    UPDATE public.coordinator_invites SET status = 'accepted', accepted_at = NOW() WHERE email = NEW.email;
  END IF;

  IF EXISTS (SELECT 1 FROM public.teacher_invites WHERE email = NEW.email AND status = 'pending') THEN
    UPDATE public.profiles SET is_teacher = TRUE WHERE id = NEW.id;
    INSERT INTO public.user_roles (user_id, role) VALUES (NEW.id, 'teacher') ON CONFLICT DO NOTHING;
    UPDATE public.teacher_invites SET status = 'accepted', accepted_at = NOW() WHERE email = NEW.email;
  END IF;

  RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

DROP TRIGGER IF EXISTS on_new_profile_check_invites ON public.profiles;
CREATE TRIGGER on_new_profile_check_invites
  AFTER INSERT ON public.profiles
  FOR EACH ROW EXECUTE FUNCTION public.handle_new_profile_invite();

